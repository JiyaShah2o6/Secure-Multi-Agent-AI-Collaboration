    expected_decision: str = "ALLOW"   # "ALLOW", "BLOCK", "RESTRICT", "REVIEW_REQUIRED"
    expected_risk: str = "LOW"         # "LOW", "MEDIUM", "HIGH"
    data_retrieval_allowed: bool = True  # True if protected customer data should be returned
    expected_released_fields: set[str] = field(default_factory=set)

    # Security Pattern Ground Truth
    is_security_threat: bool = False   # Positive class for security pattern detection
    expected_threat_labels: tuple[str, ...] = ()


