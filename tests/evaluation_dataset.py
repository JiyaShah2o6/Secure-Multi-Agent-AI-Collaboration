@dataclass(frozen=True)
class EvaluationScenario:
    id: str
    category: str
    description: str

    # Scenario Inputs
    customer_id: str
    requested_fields: list[str]
    purpose: str
    token_limit: int = 100
    sender: str = "AgentA"
    receiver: str = "AgentB"

    # Expected Governance & Execution Results
